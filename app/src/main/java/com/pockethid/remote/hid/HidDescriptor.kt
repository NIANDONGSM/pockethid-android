package com.pockethid.remote.hid

/**
 * Composite Bluetooth HID descriptor:
 * report 1 = boot-style keyboard (8 bytes), report 2 = relative mouse (4 bytes).
 */
object HidDescriptor {
    const val KEYBOARD_REPORT_ID = 1
    const val MOUSE_REPORT_ID = 2

    val bytes: ByteArray = byteArrayOf(
        // Keyboard
        0x05, 0x01, // Usage Page (Generic Desktop)
        0x09, 0x06, // Usage (Keyboard)
        0xA1.toByte(), 0x01, // Collection (Application)
        0x85.toByte(), KEYBOARD_REPORT_ID.toByte(), // Report ID
        0x05, 0x07, // Usage Page (Keyboard)
        0x19, 0xE0.toByte(), 0x29, 0xE7.toByte(), // Modifier usages
        0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95.toByte(), 0x08,
        0x81.toByte(), 0x02, // Input (Data,Var,Abs)
        0x95.toByte(), 0x01, 0x75, 0x08,
        0x81.toByte(), 0x01, // Reserved byte
        0x95.toByte(), 0x05, 0x75, 0x01,
        0x05, 0x08, 0x19, 0x01, 0x29, 0x05,
        0x91.toByte(), 0x02, // LED output
        0x95.toByte(), 0x01, 0x75, 0x03,
        0x91.toByte(), 0x01, // LED padding
        0x95.toByte(), 0x06, 0x75, 0x08,
        0x15, 0x00, 0x25, 0x65,
        0x05, 0x07, 0x19, 0x00, 0x29, 0x65,
        0x81.toByte(), 0x00, // Six keycodes
        0xC0.toByte(),

        // Mouse
        0x05, 0x01, // Usage Page (Generic Desktop)
        0x09, 0x02, // Usage (Mouse)
        0xA1.toByte(), 0x01, // Collection (Application)
        0x85.toByte(), MOUSE_REPORT_ID.toByte(), // Report ID
        0x09, 0x01, // Usage (Pointer)
        0xA1.toByte(), 0x00, // Collection (Physical)
        0x05, 0x09, 0x19, 0x01, 0x29, 0x03, // Three buttons
        0x15, 0x00, 0x25, 0x01,
        0x95.toByte(), 0x03, 0x75, 0x01,
        0x81.toByte(), 0x02,
        0x95.toByte(), 0x01, 0x75, 0x05,
        0x81.toByte(), 0x01,
        0x05, 0x01,
        0x09, 0x30, 0x09, 0x31, 0x09, 0x38, // X, Y, wheel
        0x15, 0x81.toByte(), 0x25, 0x7F,
        0x75, 0x08, 0x95.toByte(), 0x03,
        0x81.toByte(), 0x06, // Input (Data,Var,Rel)
        0xC0.toByte(),
        0xC0.toByte(),
    )
}
